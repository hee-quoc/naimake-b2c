export function getTemplate(id: string): Template | undefined {
  return TEMPLATES.find((t) => t.id === id)
}

export function templateDuration(t: Template): number {
  return t.scenes.reduce((sum, s) => sum + s.duration, 0)
}

/** The image shown on cards before a preview plays. */
export function posterPhoto(t: Template): string | undefined {
  const first = t.scenes[0]
  return t.mediaSlots.find((s) => s.id === first.media)?.photo
}
